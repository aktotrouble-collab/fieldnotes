// Run: node test-customizations.js
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const E = require('./game-engine.js');
const L = require('./league-engine.js');
const {createStore,KEY} = require('./customizations.js');
const values = new Map();
const storage = {getItem:key=>values.get(key) ?? null,setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
const C = createStore(storage,E);
const root = {};
root.window = root;
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'players-data.js'),'utf8'),root);
const base = root.MLB_PLAYERS;
const pristine = JSON.stringify(base);
const batter = base.batters.find(p=>p.team === 'LAD');
const pitcher = base.pitchers.find(p=>p.team === 'LAD');
const edited = {...batter,name:'Browser Test Batter',power:150,height:85,heightManual:true,weight:260,weightManual:true};
C.savePlayer(base.year,'batters',batter,edited);
C.savePlayer(base.year,'pitchers',pitcher,{...pitcher,velo:125,arm:140,field:110});
const data = C.data(base);
assert.equal(data.batters.find(p=>p.id===batter.id).power,150);
assert.equal(C.data({...base,year:2015}).batters.find(p=>p.id===batter.id).power,batter.power,'Season overrides are isolated');
assert.equal(JSON.stringify(base),pristine,'Source data is never mutated');
assert.equal(createStore(storage,E).data(base).batters.find(p=>p.id===batter.id).name,edited.name,'New page/store reads persistent edits');
const meta = {name:'Browser Dodgers',abbr:'BD',color:'#123456',park:'yankees'};
C.saveMetadata(base.year,'LAD',meta);
assert.equal(C.metadata(base.year,'LAD',{name:'Original'}).name,meta.name);
C.saveMetadata(2015,'ATH',meta);
assert.equal(C.metadata(2015,'OAK',{}).name,meta.name,'Historic club aliases share team overrides');
const descriptors = L.mlbDescriptors(['LAD','NYY']).map(d=>({...C.metadata(base.year,d.code,d)}));
const league = L.createLeague({name:'Test',source:'mlb',year:base.year,seed:1,settings:{gamesPerTeam:2},teams:descriptors},data);
const find = (team,id) => ['lineup','bench','rotation','bullpen'].flatMap(k=>team.roster[k]).find(p=>p.mlb===id);
const b = find(league.teams[0],batter.id);
assert(b,'Boosted MLB batter is available in new league');
assert.equal(b.power,150);
assert.equal(b.heightManual,true);
const config = L.gameConfig(league,L.pendingGames(league)[0]);
const gameTeam = [config.away,config.home].find(t=>[...t.lineup,...t.bench].some(p=>p.mlb===batter.id));
const normalized = E.createGame({away:gameTeam,home:gameTeam,park:'dodgers',seed:2});
assert.equal([...normalized.teams[0].lineup,...normalized.teams[0].bench].find(p=>p.mlb===batter.id).height,85,'Custom dimensions survive game normalization');
assert.equal(find(league.teams[0],pitcher.id).arm,140,'Pitcher non-pitching ratings survive roster construction');
const snapshot = JSON.stringify(league);
C.savePlayer(base.year,'batters',batter,{...batter,power:175,name:'Updated Batter'});
assert.equal(JSON.stringify(league),snapshot,'Existing league remains unchanged automatically');
league.stats.reg.bat[`m${batter.id}`] = {team:0,name:edited.name,pa:10,h:4};
league.rec[0].w = 2;
const updated = C.updateLeague(league,{[base.year]:base},Object.fromEntries(L.mlbDescriptors(['LAD','NYY']).map(t=>[t.code,t])));
assert.equal(find(updated.teams[0],batter.id).power,175,'Explicit update refreshes current players');
assert.deepEqual(updated.rec,league.rec,'Records are retained');
assert.deepEqual(updated.schedule,league.schedule,'Schedule is retained');
assert.equal(updated.stats.reg.bat[`m${batter.id}`].h,4,'Accumulated numbers are retained');
assert.equal(updated.stats.reg.bat[`m${batter.id}`].name,'Updated Batter','Stat display names follow stable MLB identity');
C.resetPlayer(base.year,'batters',batter.id);
assert.equal(C.data(base).batters.find(p=>p.id===batter.id).power,batter.power);
const reverted = C.updateLeague(updated,{[base.year]:base},Object.fromEntries(L.mlbDescriptors(['LAD','NYY']).map(t=>[t.code,t])));
assert.equal(find(reverted.teams[0],batter.id).power,batter.power,'Explicit update also applies resets');
assert.equal(find(reverted.teams[0],batter.id).height,E.playerHeight(batter),'Reset restores physical dimensions');
C.resetTeam(base,'LAD');
assert.deepEqual(C.metadata(base.year,'LAD',{name:'Original'}),{name:'Original'});
assert.equal(C.data(base).pitchers.find(p=>p.id===pitcher.id).velo,pitcher.velo,'Team reset includes pitchers');
const custom = E.generateTeam('Fictional','balanced',99);
Object.assign(custom,{customId:'custom-test',color:'#176442',abbr:'FIC',park:'dodgers'});
for(const group of ['lineup','bench','pitchers']) custom[group].forEach((p,i)=>p.customPlayerId=`test:${group}:${i}`);
C.saveFictional(custom);
const originalPower = custom.lineup[0].power;
const originalName = custom.lineup[0].name;
custom.lineup[0].power = 200;
custom.lineup[0].name = 'Renamed';
C.saveFictional(custom);
assert.equal(C.fictional()[0].lineup[0].power,200);
const customLeague = L.createLeague({seed:3,settings:{gamesPerTeam:2},teams:[{name:custom.name,roster:custom},{name:'Opponent'}]});
assert.equal(customLeague.teams[0].customId,'custom-test');
customLeague.stats.reg.bat[custom.lineup[0].customPlayerId] = {name:'Renamed',team:0,pa:15,h:3};
const staff = [...customLeague.teams[0].roster.rotation,...customLeague.teams[0].roster.bullpen].filter(p=>p.customPlayerId);
assert.equal(new Set(staff.map(p=>p.customPlayerId)).size,staff.length,'Imported custom starters are not duplicated in the bullpen');
const customConfig = L.gameConfig(customLeague,L.pendingGames(customLeague)[0]);
const customGame = E.createGame(customConfig);
customGame.score = [1,0];
const extracted = L.extract(customGame);
assert(extracted.sides.flatMap(s=>s.bat).some(p=>p.customPlayerId===custom.lineup[0].customPlayerId),'Stable fictional identity survives game/box-score extraction');
C.resetFictional(custom.customId,custom.lineup[0].customPlayerId);
assert.equal(C.fictional()[0].lineup[0].power,originalPower,'Individual fictional player reset');
const refreshed = C.updateLeague(customLeague,{}, {});
assert.equal(refreshed.teams[0].roster.lineup[0].power,originalPower);
assert.equal(refreshed.stats.reg.bat[custom.lineup[0].customPlayerId].name,originalName);
assert.equal(refreshed.stats.reg.bat[custom.lineup[0].customPlayerId].pa,15,'Fictional player renames retain accumulated statistics');
C.resetFictional(custom.customId);
assert.equal(C.fictional()[0].lineup[0].name,originalName,'Full fictional team reset retains original creation snapshot');
C.removeFictional(custom.customId);
assert.equal(C.fictional().length,0);
storage.setItem('unrelated','preserve');
C.resetAll();
assert.equal(storage.getItem(KEY),null);
assert.equal(storage.getItem('unrelated'),'preserve','Reset all touches only customization storage');
assert.throws(()=>createStore({getItem:()=>'{broken',setItem(){},removeItem(){}},E).read(),SyntaxError,'Corrupt storage is reported, not silently replaced');
assert.throws(()=>createStore({getItem:()=>null,setItem(){throw new Error('Storage full');},removeItem(){}},E).savePlayer(base.year,'batters',batter,edited),/Storage full/,'Failed saves surface explicitly');
for(const page of ['game.html','league.html','customization.html']) {
  assert.match(fs.readFileSync(path.join(__dirname,page),'utf8'),/src="customizations.js"/,`${page} shares the browser store`);
}
for(const file of ['dashboard.html','game.html','league.html','customization.html']) {
  const html = fs.readFileSync(path.join(__dirname,file),'utf8');
  for(const match of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) new vm.Script(match[1],{filename:file});
}
for(const file of ['customizations.js','customization-ui.js','browser-dialog.js']) new vm.Script(fs.readFileSync(path.join(__dirname,file),'utf8'),{filename:file});
assert.match(fs.readFileSync(path.join(__dirname,'dashboard.html'),'utf8'),/frames\[tab\]/,'Tab switches retain existing iframe state');
console.log('Passed: persistent seasonal overrides, immutable defaults, new/existing leagues, explicit refresh, dimensions, pitcher ratings, fictional teams, scoped resets and storage failures.');
