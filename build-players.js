/* Downloads Baseball Savant + MLB Stats API data and writes players-data.js.
   Run:  node build-players.js [year]      (default: the most recent season with data)
   Ratings: 50 = MLB average, ~100 = best in the league, floor of 20. Small samples are regressed toward 50. */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

function heightInches(value) {
  const match = /^(\d+)'\s*(\d+)"$/.exec(value || '');
  if (!match) throw new Error(`Invalid MLB height: ${value}`);
  return Number(match[1]) * 12 + Number(match[2]);
}

function weightPounds(value) {
  const weight = Number(value);
  if (!Number.isFinite(weight) || weight <= 0) throw new Error(`Invalid MLB weight: ${value}`);
  return weight;
}

function writeHeights(people) {
  const file = path.join(__dirname, 'player-heights.js');
  if (fs.existsSync(file)) delete require.cache[require.resolve(file)];
  const heights = fs.existsSync(file) ? JSON.parse(JSON.stringify(require(file))) : {};
  for (const p of people) heights[p.id] = heightInches(p.height);
  fs.writeFileSync(file, `/* MLB Stats API listed heights in inches. Generated by build-players.js. */\n(function(root){const heights=${JSON.stringify(heights)};if(typeof module!=="undefined"&&module.exports)module.exports=heights;else root.MLB_HEIGHTS=heights;})(typeof window!=="undefined"?window:globalThis);\n`);
  const weightFile = path.join(__dirname, 'player-weights.js');
  if (fs.existsSync(weightFile)) delete require.cache[require.resolve(weightFile)];
  const weights = fs.existsSync(weightFile) ? JSON.parse(JSON.stringify(require(weightFile))) : {};
  for (const p of people) weights[p.id] = weightPounds(p.weight);
  fs.writeFileSync(weightFile, `/* MLB Stats API listed weights in pounds. Generated by build-players.js. */\n(function(root){const weights=${JSON.stringify(weights)};if(typeof module!=="undefined"&&module.exports)module.exports=weights;else root.MLB_WEIGHTS=weights;})(typeof window!=="undefined"?window:globalThis);\n`);
}

async function refreshHeights() {
  const files = [path.join(__dirname, 'players-data.js'), ...fs.readdirSync(path.join(__dirname, 'seasons')).filter((f) => /^players-\d+\.js$/.test(f)).map((f) => path.join(__dirname, 'seasons', f))];
  const datasets = files.map((file) => {
    const context = { window: {} };
    vm.runInNewContext(fs.readFileSync(file, 'utf8'), context);
    return { file, data: context.window.MLB_PLAYERS || Object.values(context.window.MLB_SEASONS)[0] };
  });
  const ids = [...new Set(datasets.flatMap(({ data }) => [...data.batters, ...data.pitchers].map((p) => p.id)))];
  const people = [];
  for (let i = 0; i < ids.length; i += 100) {
    const json = JSON.parse(await get(`https://statsapi.mlb.com/api/v1/people?personIds=${ids.slice(i, i + 100).join(',')}`));
    people.push(...json.people);
  }
  const heights = new Map(people.map((p) => [p.id, heightInches(p.height)]));
  const weights = new Map(people.map((p) => [p.id, weightPounds(p.weight)]));
  for (const id of ids) if (!heights.has(id)) throw new Error(`Missing MLB height for ${id}`);
  writeHeights(people);
  for (const { file, data } of datasets) {
    for (const p of [...data.batters, ...data.pitchers]) {
      p.height = heights.get(p.id);
      p.weight = weights.get(p.id);
    }
    const assignment = path.basename(file) === 'players-data.js' ? 'window.MLB_PLAYERS' : `(window.MLB_SEASONS = window.MLB_SEASONS || {})[${data.year}]`;
    const header = fs.readFileSync(file, 'utf8').split('\n')[0];
    fs.writeFileSync(file, `${header}\n${assignment} = ${JSON.stringify(data)};\n`);
  }
  console.log(`Updated listed MLB heights and weights for ${ids.length} unique players across ${datasets.length} datasets.`);
}

const SAVANT = 'https://baseballsavant.mlb.com';
const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));

async function get(url) {
  const res = await fetch(url, { headers: { 'User-Agent': 'FieldNotes-build-players' } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { cell += '"'; i += 1; }
      else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(cell); cell = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i += 1;
      row.push(cell); cell = '';
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
    } else cell += ch;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  const head = rows.shift().map((h) => h.replace(/^\uFEFF/, ''));
  return rows.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const num = (v) => {
  if (v === undefined || v === null || v === '' || v === 'NA') return null;
  const n = Number(v);
  return Number.isFinite(n) ? n : null;
};

const mean = (a) => a.reduce((s, v) => s + v, 0) / a.length;
const sd = (a) => { const m = mean(a); return Math.sqrt(mean(a.map((v) => (v - m) ** 2))) || 1; };

// z-score function built from a reference population.
function zer(values) {
  const clean = values.filter((v) => v !== null && Number.isFinite(v));
  const m = mean(clean);
  const s = sd(clean);
  return (v) => (v === null || v === undefined ? 0 : (v - m) / s);
}

const flip = (fn) => (v) => -fn(v);
// No attribute drops below FLOOR: a 0 would mean a player who can't run or throw.
const FLOOR = 20;
// Small samples are regressed toward average: weight = n / (n + k), so 40 PA says little and 600 PA says nearly everything.
const shrink = (n, k) => n / (n + k);
const rate = (z, w = 1) => Math.max(FLOOR, Math.round(50 + (50 / 3) * z * w));
const up = (legacy) => Math.max(FLOOR, Math.round(50 + (legacy - 50) / 0.6));
const fullName = (lastFirst) => {
  const [last, first] = String(lastFirst).split(',').map((s) => s.trim());
  return first ? `${first} ${last}` : last;
};

async function savant(year, type, selections, min) {
  const url = `${SAVANT}/leaderboard/custom?year=${year}&type=${type}&filter=&min=${min}&selections=${selections.join(',')}&chart=false&r=no&csv=true`;
  return parseCsv(await get(url));
}

// historical: use the team a player spent the most games with that season instead of his current team.
async function bios(ids, year, historical) {
  const out = new Map();
  const people = [];
  for (let i = 0; i < ids.length; i += 100) {
    const chunk = ids.slice(i, i + 100);
    const json = JSON.parse(await get(`https://statsapi.mlb.com/api/v1/people?personIds=${chunk.join(',')}&hydrate=currentTeam,stats(group=[fielding,hitting,pitching],type=[season],season=${year})`));
    for (const p of json.people || []) {
      people.push(p);
      // Games played at each fielding position this season; used for multi-position eligibility.
      const games = {};
      const byTeam = {};
      for (const group of p.stats || []) {
        for (const split of group.splits || []) {
          const abbr = split.position && split.position.abbreviation;
          if (abbr && abbr !== 'P' && abbr !== 'DH') games[abbr] = (games[abbr] || 0) + (split.stat.gamesPlayed || 0);
          if (split.team && split.team.id) byTeam[split.team.id] = (byTeam[split.team.id] || 0) + (split.stat.gamesPlayed || 0);
        }
      }
      const seasonTeam = Object.entries(byTeam).sort((a, b) => b[1] - a[1])[0];
      out.set(String(p.id), {
        bats: p.batSide && p.batSide.code, throws: p.pitchHand && p.pitchHand.code,
        pos: p.primaryPosition && p.primaryPosition.abbreviation,
        team: historical ? '' : p.currentTeam && (p.currentTeam.abbreviation || p.currentTeam.name),
        teamId: historical ? (seasonTeam ? Number(seasonTeam[0]) : null) : p.currentTeam && p.currentTeam.id,
        games, height: heightInches(p.height), weight: weightPounds(p.weight)
      });
    }
    writeHeights(people);
  }
  return out;
}

async function teamAbbr(year, historical) {
  const json = JSON.parse(await get(`https://statsapi.mlb.com/api/v1/teams?sportId=1${historical ? `&season=${year}` : ''}`));
  return new Map(json.teams.map((t) => [t.id, t.abbreviation]));
}

const FIRST_YEAR = 2015;
const FIRST_ARM_YEAR = 2020;

async function build(year, historical) {
  const BAT = ['pa', 'k_percent', 'bb_percent', 'batting_avg', 'on_base_percent', 'slg_percent', 'exit_velocity_avg', 'launch_angle_avg',
    'barrel_batted_rate', 'hard_hit_percent', 'sprint_speed', 'oz_swing_percent', 'swing_percent', 'iz_contact_percent', 'avg_swing_speed', 'home_run'];
  const PIT = ['p_game', 'p_formatted_ip', 'p_starts', 'k_percent', 'bb_percent', 'ff_avg_speed', 'sl_avg_speed', 'whiff_percent', 'oz_swing_percent', 'p_era', 'groundballs_percent'];

  let useYear = year;
  let batRows = await savant(useYear, 'batter', BAT, 25);
  if (!historical && batRows.length < 100) { useYear -= 1; batRows = await savant(useYear, 'batter', BAT, 25); }
  const pitRows = await savant(useYear, 'pitcher', PIT, 5);
  const armCsv = (y) => get(`${SAVANT}/leaderboard/arm-strength?type=player&year=${y}&minThrows=10&pos=&team=&csv=true`).then(parseCsv).catch(() => []);
  let armRows = await armCsv(useYear);
  // Arm strength is only tracked from 2020. Earlier seasons borrow each player's arm from the first tracked season
  // (arm strength changes slowly); players who never appear there get a position-based guess below.
  let armYear = useYear;
  if (armRows.length < 50) {
    armYear = FIRST_ARM_YEAR;
    armRows = await armCsv(armYear);
  }
  // Outs Above Average only exists from 2016; 2015 fielders stay at a neutral 50 FLD.
  const oaaRows = await get(`${SAVANT}/leaderboard/outs_above_average?type=Fielder&startYear=${useYear}&endYear=${useYear}&split=no&team=&range=year&min=10&pos=&roles=&viz=hide&csv=true`).then(parseCsv).catch(() => []);
  console.log(`season ${useYear}: ${batRows.length} batters, ${pitRows.length} pitchers, ${armRows.length} arm rows (${armYear}), ${oaaRows.length} OAA rows`);

  const ids = [...new Set([...batRows, ...pitRows].map((r) => r.player_id))];
  const [bio, teams] = await Promise.all([bios(ids, useYear, historical), teamAbbr(useYear, historical)]);

  const arm = new Map(armRows.map((r) => [r.player_id, r]));
  const oaa = new Map(oaaRows.map((r) => [r.player_id, num(r.outs_above_average)]));

  // Reference populations (everyone with a real sample) for the z-scores.
  const ref = batRows.filter((r) => num(r.pa) >= 100).map((r) => Object.fromEntries(BAT.map((k) => [k, num(r[k])])));
  const col = (k) => ref.map((r) => r[k]);
  const zK = zer(col('k_percent')), zBB = zer(col('bb_percent')), zAvg = zer(col('batting_avg'));
  const zBarrel = zer(col('barrel_batted_rate')), zEV = zer(col('exit_velocity_avg')), zSLG = zer(col('slg_percent'));
  const zHH = zer(col('hard_hit_percent')), zChase = zer(col('oz_swing_percent')), zContact = zer(col('iz_contact_percent'));
  const zSpeed = zer(col('sprint_speed')), zSwing = zer(col('swing_percent')), zBatSpeed = zer(col('avg_swing_speed'));

  const armGroup = (pos) => (['LF', 'CF', 'RF'].includes(pos) ? 'arm_of' : ['1B', '2B', '3B', 'SS'].includes(pos) ? 'arm_inf' : 'arm_overall');
  const armStats = {};
  for (const g of ['arm_of', 'arm_inf', 'arm_overall']) armStats[g] = zer(armRows.map((r) => num(r[g])));
  const oaaZ = zer([...oaa.values()]);

  const batters = [];
  for (const r of batRows) {
    const b = bio.get(r.player_id);
    if (!b) throw new Error(`Missing MLB biography for ${r.player_id}`);
    if (b.pos === 'P') continue; // pitchers who batted (pre-2022 NL) aren't hitters
    const pa = num(r.pa);
    // Position = where he played the most games that season (current primary position only if there's little fielding data).
    const topField = Object.entries(b.games || {}).sort((x, y) => y[1] - x[1])[0];
    const bioPos = b.pos && b.pos !== 'P' && b.pos !== 'TWP' ? b.pos : 'DH';
    const pos = topField && topField[1] >= 20 ? topField[0] : bioPos;
    const wBat = shrink(pa, 150);
    const sprint = num(r.sprint_speed);
    const speed = sprint === null ? 42 : rate(zSpeed(sprint));
    const power = rate(0.35 * zBarrel(num(r.barrel_batted_rate)) + 0.25 * zEV(num(r.exit_velocity_avg)) + 0.2 * zSLG(num(r.slg_percent)) + 0.2 * (num(r.avg_swing_speed) === null ? 0 : zBatSpeed(num(r.avg_swing_speed))));
    const contact = rate(-0.5 * zK(num(r.k_percent)) + 0.3 * zContact(num(r.iz_contact_percent)) + 0.2 * zAvg(num(r.batting_avg)), wBat);
    const eye = rate(0.55 * zBB(num(r.bb_percent)) - 0.45 * zChase(num(r.oz_swing_percent)), wBat);
    const armRow = arm.get(r.player_id);
    const group = armGroup(pos);
    const armVal = armRow ? num(armRow[group]) ?? num(armRow.arm_overall) : null;
    const armRating = armVal === null ? (pos === 'C' ? 58 : ['SS', '3B', 'RF'].includes(pos) ? 52 : 50) : rate(armStats[group](armVal));
    const oaaVal = oaa.get(r.player_id);
    const field = oaaVal === null || oaaVal === undefined ? 50 : Math.max(FLOOR, Math.round(50 + 3 * oaaVal));
    const risk = Math.max(FLOOR, Math.round(50 + 0.5 * (speed - 50) + 5 * zSwing(num(r.swing_percent))));
    const alt = Object.entries(b.games || {}).filter(([p, n]) => p !== pos && n >= 10).sort((x, y) => y[1] - x[1]).map(([p]) => p);
    batters.push({
      id: Number(r.player_id), name: fullName(r['last_name, first_name']), team: teams.get(b.teamId) || b.team || '', pos, natural: pos, alt,
      bats: b.bats || 'R', throws: b.throws || 'R', pa, height: b.height, weight: b.weight,
      contact, power, eye, speed, arm: armRating, field, risk,
      loft: Math.round(clamp(num(r.launch_angle_avg) ?? 12, 0, 25) * 10) / 10,
      stat: { avg: num(r.batting_avg), obp: num(r.on_base_percent), slg: num(r.slg_percent), hr: num(r.home_run), ev: num(r.exit_velocity_avg), k: num(r.k_percent), bb: num(r.bb_percent), brl: num(r.barrel_batted_rate), spd: sprint }
    });
  }

  const pref = pitRows.filter((r) => num(r.p_game) >= 8);
  const zpK = zer(pref.map((r) => num(r.k_percent))), zpBB = zer(pref.map((r) => num(r.bb_percent)));
  const zpW = zer(pref.map((r) => num(r.whiff_percent))), zpGB = zer(pref.map((r) => num(r.groundballs_percent)));
  const pitchers = [];
  for (const r of pitRows) {
    const b = bio.get(r.player_id);
    if (!b) throw new Error(`Missing MLB biography for ${r.player_id}`);
    const g = num(r.p_game) || 1;
    const ip = num(r.p_formatted_ip) || 0;
    const ipPerG = ip / g;
    const wPit = shrink(ip, 45);
    const starts = num(r.p_starts) || 0;
    const role = starts >= Math.max(3, g * 0.4) || ipPerG >= 4 ? 'SP' : 'RP';
    const velo = num(r.ff_avg_speed) ?? (num(r.sl_avg_speed) ? num(r.sl_avg_speed) + 9 : 92);
    pitchers.push({
      id: Number(r.player_id), name: fullName(r['last_name, first_name']), team: teams.get(b.teamId) || b.team || '', role,
      throws: b.throws || 'R', ip, height: b.height, weight: b.weight,
      velo: Math.max(FLOOR, Math.round(50 + (velo - 93) * 8)), mph: Math.round(velo * 10) / 10,
      control: rate(-zpBB(num(r.bb_percent)), wPit),
      movement: rate(0.6 * zpW(num(r.whiff_percent)) + 0.25 * zpK(num(r.k_percent)) + 0.15 * zpGB(num(r.groundballs_percent)), wPit),
      stamina: up(clamp(Math.round(role === 'SP' ? 40 + ipPerG * 5 : 22 + ipPerG * 8), 20, 80)),
      stat: { era: num(r.p_era), k: num(r.k_percent), bb: num(r.bb_percent), g, ip }
    });
  }

  batters.sort((a, b) => b.pa - a.pa);
  pitchers.sort((a, b) => b.ip - a.ip);
  const payload = JSON.stringify({ year: useYear, built: new Date().toISOString().slice(0, 10), batters, pitchers });
  const header = `/* Generated by build-players.js from Baseball Savant and the MLB Stats API (${useYear} season). Do not edit by hand. */\n`;
  let out, file;
  if (historical) {
    file = path.join('seasons', `players-${useYear}.js`);
    out = `${header}(window.MLB_SEASONS = window.MLB_SEASONS || {})[${useYear}] = ${payload};\n`;
    fs.mkdirSync(path.join(__dirname, 'seasons'), { recursive: true });
  } else {
    file = 'players-data.js';
    out = `${header}window.MLB_PLAYERS = ${payload};\n`;
  }
  fs.writeFileSync(path.join(__dirname, file), out);
  console.log(`wrote ${file}: ${batters.length} batters, ${pitchers.length} pitchers, ${(out.length / 1024).toFixed(0)} KB`);
  return useYear;
}

/* node build-players.js            -> players-data.js for the latest season (the nightly job)
   node build-players.js --measurements -> refresh listed heights/weights in every existing season and lookup file
   node build-players.js --heights  -> alias for --measurements
   node build-players.js 2019       -> seasons/players-2019.js
   node build-players.js --all      -> every past season from 2015 up to the latest, skipping files that exist */
async function main() {
  const arg = process.argv[2];
  if (arg === '--heights' || arg === '--measurements') return refreshHeights();
  if (arg === '--all') {
    const latest = await build(new Date().getFullYear(), false);
    for (let y = FIRST_YEAR; y < latest; y += 1) {
      if (fs.existsSync(path.join(__dirname, 'seasons', `players-${y}.js`))) continue;
      await build(y, true);
    }
  } else if (arg) await build(Number(arg), true);
  else await build(new Date().getFullYear(), false);
}

main().catch((e) => { console.error(e); process.exit(1); });
