// Run: node test-added-players.js
const assert = require('node:assert/strict');
const E = require('./game-engine.js');
const L = require('./league-engine.js');
const {createStore} = require('./customizations.js');
const values = new Map();
const storage = {getItem:k=>values.get(k) ?? null,setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k)};
const C = createStore(storage,E,L);
const base = {year:2026,batters:[],pitchers:[]};
const player = {name:'Added Star',pos:'SS',role:'SP',bats:'R',throws:'R',height:75,weight:210,heightManual:true,weightManual:true};
for(const key of ['contact','power','eye','speed','arm','field','risk','loft','velo','control','movement','stamina'])player[key]=150;
const id = C.saveAdded(2026,'batters',player,'NYY');
assert.equal(C.data(base).batters[0].team,'NYY');
assert.equal(C.data(base).batters[0].id,id);
assert.equal(createStore(storage,E,L).added(2026)[0].player.name,player.name,'Added players survive new stores');
assert.equal(C.data({...base,year:2025}).batters.length,0,'MLB additions are seasonal');
const team = E.generateTeam('Fictional','balanced',42);
Object.assign(team,{customId:'custom-test',color:'#176442',abbr:'FIC'});
for(const group of ['lineup','bench','pitchers'])team[group].forEach((p,i)=>p.customPlayerId=`base:${group}:${i}`);
C.saveFictional(team);
C.saveAdded(2026,'batters',player,team.customId,id);
assert.equal(C.data(base).batters.length,0,'Reassignment removes player from former club');
const selected = C.fictional()[0];
assert(selected.lineup.some(p=>p.customPlayerId===id && p.pos==='SS'),'Strong added batter automatically starts at natural position');
assert.deepEqual(E.validateTeam(selected),[],'Automatic selection maintains legal lineup');
assert.equal(C.read().fictional[team.customId].team.lineup.length,9,'Automatic selection does not mutate stored original roster');
const pitcherId = C.saveAdded(2026,'pitchers',{...player,name:'Added Ace'},team.customId);
assert.equal(C.fictional()[0].pitchers[0].customPlayerId,pitcherId,'Added ace wins starting role');
const lg = L.createLeague({seed:1,settings:{gamesPerTeam:2},teams:[{name:'Fictional',roster:C.fictional()[0]},{name:'Opponent'}]});
assert(lg.teams[0].roster.lineup.some(p=>p.customPlayerId===id));
assert(lg.teams[0].roster.rotation.some(p=>p.customPlayerId===pitcherId));
const snapshot=JSON.stringify(lg);
C.saveAdded(2026,'batters',{...player,power:200},'',id);
assert.equal(JSON.stringify(lg),snapshot,'Existing league rosters do not change on reassignment');
assert.equal(C.fictional()[0].lineup.some(p=>p.customPlayerId===id),false);
C.resetAdded(id);
assert.equal(C.added(2026).find(p=>p.id===id).player.power,150);
assert.equal(C.added(2026).find(p=>p.id===id).team,'','Reset ratings retains team assignment');
C.resetFictional(team.customId);
assert.equal(C.added(2026).find(p=>p.id===pitcherId).team,'','Team reset detaches additions without deleting them');
C.saveAdded(2026,'batters',player,'NYY',id);
C.resetTeam(base,'NYY');
assert.equal(C.data(base).batters.length,0);
C.removeAdded(id);
assert.equal(C.added(2026).some(p=>p.id===id),false);
assert.throws(()=>C.saveAdded(2026,'batters',{...player,power:NaN},'NYY'),/Invalid power/);
assert.throws(()=>C.saveAdded(2026,'batters',player,'missing'),/existing team/);
console.log('Passed: added batters/pitchers, browser persistence, seasonal MLB pools, reassignment, fictional auto-selection, legal rosters, league snapshots, resets and deletion.');
