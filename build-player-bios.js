/* Refresh immutable MLB birth/debut dates and selected-year salary facts.
   Run: node build-player-bios.js. Never imports subsequent-season performance. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
async function json(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`HTTP ${response.status}: ${url}`);
  return response.json();
}
async function main() {
  const files = ['players-data.js', ...fs.readdirSync(path.join(__dirname,'seasons')).filter(f=>/^players-\d+\.js$/.test(f)).map(f=>path.join('seasons',f))];
  const ids = new Set(), datasets=[];
  for (const file of files) {
    const context = {window:{}};
    vm.runInNewContext(fs.readFileSync(path.join(__dirname,file),'utf8'),context);
    const data = context.window.MLB_PLAYERS || Object.values(context.window.MLB_SEASONS)[0];
    datasets.push({file,data,header:fs.readFileSync(path.join(__dirname,file),'utf8').split('\n')[0]});
    for (const p of [...data.batters,...data.pitchers]) if (Number.isInteger(p.id)) ids.add(p.id);
  }
  const all = [...ids], bios = {};
  for (let i=0;i<all.length;i+=100) {
    const data = await json(`https://statsapi.mlb.com/api/v1/people?personIds=${all.slice(i,i+100).join(',')}`);
    for (const p of data.people) {
      if (!/^\d{4}-\d{2}-\d{2}$/.test(p.birthDate)) throw new Error(`Missing birth date: ${p.id}`);
      bios[p.id] = { birthDate:p.birthDate, debut:p.mlbDebutDate || null };
    }
  }
  for (const id of all) if (!bios[id]) throw new Error(`Missing biography ${id}`);
  fs.writeFileSync(path.join(__dirname,'player-bios.js'),`/* MLB Stats API immutable birth/debut dates. Generated by build-player-bios.js. */\n(function(root){const bios=${JSON.stringify(bios)};if(typeof module!=="undefined"&&module.exports)module.exports=bios;else root.MLB_BIOS=bios;})(typeof window!=="undefined"?window:globalThis);\n`);
  for (const {file,data,header} of datasets) {
    for (const p of [...data.batters,...data.pitchers]) {
      const bio=bios[p.id];
      p.birthDate=bio.birthDate;
      p.age=data.year-Number(bio.birthDate.slice(0,4))-(bio.birthDate.slice(5)>'07-01'?1:0);
    }
    const assignment=path.basename(file)==='players-data.js'?'window.MLB_PLAYERS':`(window.MLB_SEASONS = window.MLB_SEASONS || {})[${data.year}]`;
    fs.writeFileSync(path.join(__dirname,file),`${header}\n${assignment} = ${JSON.stringify(data)};\n`);
  }
  console.log(`Imported birth dates for all ${all.length} MLB players across ${files.length} datasets.`);
}
main().catch(error=>{ console.error(error);process.exitCode=1; });
