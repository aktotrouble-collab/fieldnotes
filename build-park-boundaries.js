/* Regenerate exact game collision boundaries after changing the park art in index.html.
 * Run: node build-park-boundaries.js [--check]
 */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');
function readObject(name) {
  const start = html.indexOf(`const ${name} = {`);
  if (start < 0) throw new Error(`Missing ${name} in index.html`);
  const end = html.indexOf('\n      };', start);
  if (end < 0) throw new Error(`Missing end of ${name}`);
  return vm.runInNewContext(`${html.slice(start, end + 9)}\n${name};`);
}
const art = readObject('REFERENCE_ART');
const foulWalls = readObject('FOUL_WALLS');
const boundaries = {};
for (const [id, ref] of Object.entries(art)) {
  if (!ref.walls || !foulWalls[id]) throw new Error(`Missing wall outline for ${id}`);
  const world = ([x, y]) => [(x - ref.homeX) / ref.pixelsPerFootX, (ref.homeY - y) / ref.pixelsPerFootY];
  const outfield = ref.walls.map(world);
  const foul = foulWalls[id].map(world);
  const points = [...outfield, ...foul.slice().reverse()];
  const heights = ref.walls.slice(1).map((_, i) => {
    const h = ref.wallHeights?.[i] ?? ref.wallHeight;
    return Array.isArray(h) ? Math.max(...h) : h;
  });
  boundaries[id] = { points, heights: [...heights, ...foul.map(() => 8), 8], outfield: outfield.length - 1 };
}
const target = path.join(__dirname, 'park-walls.js');
const text = fs.readFileSync(target, 'utf8');
const line = `  root.PARK_BOUNDARIES = ${JSON.stringify(boundaries)};`;
const updated = text.includes('  root.PARK_BOUNDARIES = ')
  ? text.replace(/  root\.PARK_BOUNDARIES = [^\r\n]*/, line)
  : text.replace('  root.PARK_WALLS = PARK_WALLS;', `  root.PARK_WALLS = PARK_WALLS;\n  // Exact, closed wall outlines generated by build-park-boundaries.js from index.html.\n${line}`);
if (process.argv.includes('--check')) {
  if (updated !== text) throw new Error('Park collision outlines are stale: run node build-park-boundaries.js');
} else {
  fs.writeFileSync(target, updated);
}
console.log(`Exact collision outlines ${process.argv.includes('--check') ? 'verified' : 'generated'} for ${Object.keys(boundaries).length} parks.`);
